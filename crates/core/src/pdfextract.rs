const ENDS: [char; 9] = ['.', '!', '?', ':', '"', '”', '’', ')', ';'];

fn ends_sentence(s: &str) -> bool {
    s.trim_end().chars().last().is_some_and(|c| ENDS.contains(&c))
}

fn marker_re() -> &'static Regex {
    static R: OnceLock<Regex> = OnceLock::new();
    R.get_or_init(|| Regex::new(r"^\s*([•◦▪‣∙·●○■□–—\-*]|\d{1,3}[.)]|[a-z][.)]|\([a-z0-9]{1,3}\)|[ivx]{1,4}[.)]|\[\d{1,3}\])\s+").unwrap())
}

fn caption_re() -> &'static Regex {
    static R: OnceLock<Regex> = OnceLock::new();
    R.get_or_init(|| Regex::new(r"(?i)^(figure|fig\.|table|listing|algorithm)\s*\d+").unwrap())
}

fn list_marker(s: &str) -> Option<(String, usize)> {
    let m = marker_re().captures(s)?;
    let mark = &m[1];
    let kind = if "•◦▪‣∙·●○■□–—-*".contains(mark) { "bullet" } else { "number" };
    Some((kind.into(), m.get(0).unwrap().end()))
}

fn has_words(s: &str) -> bool {
    s.split_whitespace().any(|w| w.chars().filter(|c| c.is_alphabetic()).count() >= 2)
}

fn word_count(s: &str) -> usize {
    s.split_whitespace().filter(|w| w.chars().filter(|c| c.is_alphabetic()).count() >= 2).count()
}

type Bx = [f64; 4]; // left, top, right, bottom

fn union(a: Bx, b: Bx) -> Bx {
    [a[0].min(b[0]), a[1].min(b[1]), a[2].max(b[2]), a[3].max(b[3])]
}

fn near(a: &Bx, b: &Bx, m: f64) -> bool {
    a[0] <= b[2] + m && b[0] <= a[2] + m && a[1] <= b[3] + m && b[1] <= a[3] + m
}

fn line_box(l: &Line) -> Bx {
    [l.x0, l.ink.0, l.x1, l.ink.1]
}

fn center_in(l: &Line, b: &Bx, pad: f64) -> bool {
    let (cx, cy) = ((l.x0 + l.x1) / 2.0, (l.ink.0 + l.ink.1) / 2.0);
    cx >= b[0] - pad && cx <= b[2] + pad && cy >= b[1] - pad && cy <= b[3] + pad
}

#[derive(Clone, Copy, PartialEq, Debug)]
enum Kind {
    Picture,
    Figure,
    Math,
}

/// A picture in the flow: an image from the PDF, or a drawing or equation drawn from the page.
#[derive(Clone, Debug)]
struct Region {
    page: usize,
    b: Bx,
    kind: Kind,
    data: Vec<u8>,
    alt: String,
    /// The line it goes before (in reading order).
    pos: usize,
}

/// Groups of boxes that touch or nearly touch.
fn clusters(rects: &[Bx], margin: f64) -> Vec<Vec<usize>> {
    fn root(p: &mut [usize], mut x: usize) -> usize {
        while p[x] != x {
            p[x] = p[p[x]];
            x = p[x];
        }
        x
    }
    let n = rects.len();
    let mut parent: Vec<usize> = (0..n).collect();
    let mut order: Vec<usize> = (0..n).collect();
    order.sort_by(|a, b| rects[*a][0].total_cmp(&rects[*b][0]));
    for (k, &a) in order.iter().enumerate() {
        for &b in &order[k + 1..] {
            if rects[b][0] > rects[a][2] + margin {
                break;
            }
            if near(&rects[a], &rects[b], margin) {
                let (ra, rb) = (root(&mut parent, a), root(&mut parent, b));
                if ra != rb {
                    parent[ra] = rb;
                }
            }
        }
    }
    let mut groups: HashMap<usize, Vec<usize>> = HashMap::new();
    for i in 0..n {
        let r = root(&mut parent, i);
        groups.entry(r).or_default().push(i);
    }
    let mut out: Vec<Vec<usize>> = groups.into_values().collect();
    out.sort_by(|a, b| a[0].cmp(&b[0]));
    out
}

fn merge(mut rs: Vec<(Bx, Vec<usize>)>) -> Vec<(Bx, Vec<usize>)> {
    loop {
        let mut pair = None;
        'find: for a in 0..rs.len() {
            for b in a + 1..rs.len() {
                if near(&rs[a].0, &rs[b].0, 2.0) {
                    pair = Some((a, b));
                    break 'find;
                }
            }
        }
        let Some((a, b)) = pair else { return rs };
        let (bb, mb) = rs.remove(b);
        rs[a].0 = union(rs[a].0, bb);
        rs[a].1.extend(mb);
    }
}

/// Drawings (charts, plots, diagrams) with their labels, drawn from the page as pictures. A cluster of
/// paths is a drawing when the text inside it is sparse; a dense one is a table, a box or a shaded block.
fn figures(pages: &[PPage], lines: &[Line], ranges: &[Range<usize>], body: f64, used: &mut [bool], taken: &mut [Vec<bool>], render: Render, debug: bool) -> Vec<Region> {
    let mut out = vec![];
    for (k, p) in pages.iter().enumerate() {
        let area = p.width * p.height;
        let shapes: Vec<&PShape> = p.shapes.iter().filter(|s| s.2 > s.0 && s.3 > s.1 && (s.2 - s.0) * (s.3 - s.1) < 0.5 * area).take(20000).collect();
        if shapes.is_empty() {
            continue;
        }
        let rects: Vec<Bx> = shapes.iter().map(|s| [s.0, s.1, s.2, s.3]).collect();
        let marks: Vec<(f64, f64)> = ranges[k].clone().flat_map(|i| lines[i].glyphs.iter()).filter(|g| !g.space).map(|g| ((g.x0 + g.x1) / 2.0, (g.top + g.bottom) / 2.0)).collect();
        let mut cands: Vec<(Bx, Vec<usize>)> = vec![];
        for group in clusters(&rects, 6.0) {
            let visible: Vec<&PShape> = group.iter().map(|&j| shapes[j]).filter(|s| s.4 != 2).collect();
            // a bar, a curve or a marker: a shape with breadth that holds no text (a table is made of
            // rules, and its shaded cells hold text)
            let bare = visible.iter().filter(|s| (s.2 - s.0).min(s.3 - s.1) >= 2.0 && !marks.iter().any(|m| m.0 > s.0 && m.0 < s.2 && m.1 > s.1 && m.1 < s.3)).count();
            let groups = visible.iter().filter(|s| s.4 == 1).count();
            let b = group.iter().map(|&j| rects[j]).reduce(union).unwrap();
            if debug {
                eprintln!("drawing p{k} {:?} shapes {} visible {} bare {bare} groups {groups}", b.map(|v| v.round()), group.len(), visible.len());
            }
            if !(groups > 0 || (visible.len() >= 2 && bare >= 1)) {
                continue;
            }
            if b[2] - b[0] < 30.0 || b[3] - b[1] < 20.0 || (b[2] - b[0]) * (b[3] - b[1]) > 0.85 * area {
                continue;
            }
            cands.push((b, vec![]));
        }
        let mut cands = merge(cands);
        cands.retain_mut(|(b, members)| {
            let inside: Vec<usize> = ranges[k].clone().filter(|&i| !used[i] && center_in(&lines[i], b, 1.0)).collect();
            let ink: f64 = inside.iter().flat_map(|&i| lines[i].glyphs.iter()).filter(|g| !g.space).map(|g| (g.x1 - g.x0) * (g.bottom - g.top)).sum();
            let prose = inside.iter().filter(|&&i| word_count(&lines[i].text) >= 6).count();
            let cover = ink / ((b[2] - b[0]) * (b[3] - b[1]));
            if debug {
                eprintln!("  candidate {:?} lines {} cover {cover:.3} prose {prose}", b.map(|v| v.round()), inside.len());
            }
            *members = inside;
            cover <= 0.08 && (prose == 0 || (prose == 1 && cover < 0.04))
        });
        // labels just outside the drawing (axis titles, tick labels, legends), but not headings or prose
        for (b, members) in cands.iter_mut() {
            for _ in 0..3 {
                let mut grew = false;
                for i in ranges[k].clone() {
                    if used[i] || members.contains(&i) {
                        continue;
                    }
                    let l = &lines[i];
                    let words = word_count(&l.text);
                    let label = l.mono < 0.5
                        && l.size < body * 1.15
                        && words <= 4
                        && l.text.chars().count() <= 40
                        && (l.size < body * 0.95 || words <= 2)
                        && (words <= 2 || !ends_sentence(&l.text))
                        && !caption_re().is_match(&l.text)
                        && list_marker(&l.text).is_none();
                    if label && near(&line_box(l), b, 1.2 * l.size) {
                        members.push(i);
                        *b = union(*b, line_box(l));
                        grew = true;
                    }
                }
                if !grew {
                    break;
                }
            }
        }
        for (mut b, members) in merge(cands) {
            let mut pics = vec![];
            for (j, im) in p.images.iter().enumerate() {
                let ib = [im.x0, im.top, im.x1, im.bottom];
                if !taken[k][j] && near(&ib, &b, 0.0) {
                    pics.push(j);
                    b = union(b, ib);
                }
            }
            let pad = 2.0;
            let Some(png) = render(k, b[0] - pad, b[1] - pad, b[2] + pad, b[3] + pad) else { continue };
            for &i in &members {
                used[i] = true;
            }
            for j in pics {
                taken[k][j] = true;
            }
            out.push(Region { page: k, b, kind: Kind::Figure, data: png, alt: String::new(), pos: 0 });
        }
    }
    out
}

const FUNCS: [&str; 28] = [
    "sin", "cos", "tan", "cot", "sec", "csc", "log", "ln", "exp", "max", "min", "lim", "sup", "inf", "det", "arg", "mod", "dim", "ker", "deg", "gcd", "sinh", "cosh", "tanh",
    "arcsin", "arccos", "arctan", "Pr",
];

fn math_char(c: char) -> bool {
    "=+−×÷±∓≤≥≠≈≡∼≃≅∝∞∫∬∭∮∑∏∐√∂∇∆∈∉∋⊂⊃⊆⊇∪∩∧∨¬∀∃∄→←↔⇒⇐⇔↦⟨⟩‖′″⋅∘⊗⊕⊥∥∠ϵϑϕϖϱς".contains(c)
        || ('\u{391}'..='\u{3c9}').contains(&c)
        || ('\u{1d400}'..='\u{1d7ff}').contains(&c)
}

/// (math symbols, single italic letters, plain words, visible characters) of some glyphs. Tokens break
/// at spaces and symbols, between letters and digits, and where the size changes ("x²d" is x, 2, d).
fn math_stats(gs: &[G]) -> (usize, usize, usize, usize) {
    let (mut symbols, mut letters, mut words, mut solid) = (0, 0, 0, 0);
    let mut word = String::new();
    let mut italic = true;
    let mut size = 0.0f64;
    let close =|word: &mut String, italic: &mut bool, letters: &mut usize, words: &mut usize| {
        let n = word.chars().count();
        if n == 1 && *italic && word.chars().all(char::is_alphabetic) {
            *letters += 1;
        } else if n >= 3 && !*italic && word.chars().all(char::is_alphabetic) && !FUNCS.contains(&word.as_str()) {
            *words += 1;
        }
        word.clear();
        *italic = true;
    };
    for g in gs {
        if !g.space {
            solid += 1;
        }
        if g.space || math_char(g.ch) || !g.ch.is_alphanumeric() {
            close(&mut word, &mut italic, &mut letters, &mut words);
            if !g.space && math_char(g.ch) {
                symbols += 1;
            }
            continue;
        }
        let kind_changes = word.chars().last().is_some_and(|c| c.is_alphabetic() != g.ch.is_alphabetic());
        if !word.is_empty() && (kind_changes || (g.size - size).abs() > 0.5) {
            close(&mut word, &mut italic, &mut letters, &mut words);
        }
        word.push(g.ch);
        italic &= g.italic;
        size = g.size;
    }
    close(&mut word, &mut italic, &mut letters, &mut words);
    (symbols, letters, words, solid)
}

fn mathy(l: &Line) -> bool {
    let (s, i, w, _) = math_stats(&l.glyphs);
    s >= 1 && s + i >= 3 && w <= 2
}

fn math_part(l: &Line) -> bool {
    let (s, _, w, n) = math_stats(&l.glyphs);
    mathy(l) || (w == 0 && (s >= 1 || n <= 4))
}

fn eq_number(s: &str) -> bool {
    static R: OnceLock<Regex> = OnceLock::new();
    R.get_or_init(|| Regex::new(r"^\(\s*[0-9A-Za-z.\-]{1,8}\s*\)$").unwrap()).is_match(s.trim())
}

/// The box and text of a line's equation, without its number "(1)" at either end.
fn eq_part(l: &Line) -> (Bx, String) {
    let mut segs = l.segments();
    if segs.len() > 1 && eq_number(&glyph_text(&l.glyphs[segs[segs.len() - 1].2.clone()])) {
        segs.pop();
    }
    if segs.len() > 1 && eq_number(&glyph_text(&l.glyphs[segs[0].2.clone()])) {
        segs.remove(0);
    }
    let range = segs.first().map(|s| s.2.start).unwrap_or(0)..segs.last().map(|s| s.2.end).unwrap_or(0);
    let gs = &l.glyphs[range];
    let b = gs.iter().filter(|g| !g.space).fold([f64::INFINITY, f64::INFINITY, f64::NEG_INFINITY, f64::NEG_INFINITY], |b, g| union(b, [g.x0, g.top, g.x1, g.bottom]));
    (if b[0].is_finite() { b } else { line_box(l) }, glyph_text(gs))
}

/// Display equations: lines of mostly symbols and single italic letters (with the pieces above and
/// below them: limits, numerators, denominators) standing centred in their column.
fn equations(lines: &[Line], ranges: &[Range<usize>], cols: &[Vec<Col>], body: f64, used: &mut [bool], render: Render) -> Vec<Region> {
    let mut out = vec![];
    for (k, r) in ranges.iter().enumerate() {
        let mut i = r.start;
        while i < r.end {
            let l = &lines[i];
            if used[i] || l.mono > 0.5 || !mathy(l) {
                i += 1;
                continue;
            }
            let c = column_of(&cols[k], l);
            let (mut b, _) = eq_part(l);
            if b[0] < c.left + 1.5 * body {
                i += 1;
                continue;
            }
            let fits = |o: &Line, b: &Bx, above: bool| {
                let (ob, _) = eq_part(o);
                let gap = if above { b[1] - ob[3] } else { ob[1] - b[3] };
                let ok = o.mono <= 0.5 && math_part(o) && gap <= 0.9 * body && ob[2] >= b[0] - 2.0 * body && ob[0] <= b[2] + 2.0 * body && ob[0] >= c.left + body;
                if ok {
                    Some(ob)
                } else {
                    None
                }
            };
            // an equation number set on a line of its own, level with the equation
            let number = |o: &Line, b: &Bx| eq_number(&o.text) && (o.ink.0 + o.ink.1) / 2.0 > b[1] - 2.0 && (o.ink.0 + o.ink.1) / 2.0 < b[3] + 2.0;
            let (mut a, mut e) = (i, i + 1);
            while a > r.start && !used[a - 1] {
                match fits(&lines[a - 1], &b, true) {
                    Some(ob) => b = union(b, ob),
                    None if number(&lines[a - 1], &b) => {}
                    None => break,
                }
                a -= 1;
            }
            while e < r.end && !used[e] {
                match fits(&lines[e], &b, false) {
                    Some(ob) => b = union(b, ob),
                    None if number(&lines[e], &b) => {}
                    None => break,
                }
                e += 1;
            }
            let (mid, cm, cw) = ((b[0] + b[2]) / 2.0, (c.left + c.right) / 2.0, c.right - c.left);
            let centred = (mid - cm).abs() <= 0.15 * cw && b[0] - c.left >= 1.5 * body && c.right - b[2] >= 1.5 * body;
            if !centred {
                i += 1;
                continue;
            }
            let pad = 3.0;
            if let Some(png) = render(k, b[0] - pad, b[1] - pad, b[2] + pad, b[3] + pad) {
                for u in used[a..e].iter_mut() {
                    *u = true;
                }
                let alt = (a..e).filter(|&j| !eq_number(&lines[j].text)).map(|j| eq_part(&lines[j]).1).collect::<Vec<_>>().join(" ");
                out.push(Region { page: k, b, kind: Kind::Math, data: png, alt: textclean::ligatures(alt.trim()), pos: a });
            }
            i = e;
        }
    }
    out
}

/// Where a picture goes in reading order: before the first line under it in its column, or after the
/// last line above it.
fn place(lines: &[Line], ranges: &[Range<usize>], used: &[bool], r: &Region) -> usize {
    let range = ranges[r.page].clone();
    let beside = |l: &Line| l.x0 < r.b[2] && l.x1 > r.b[0];
    if let Some(i) = range.clone().find(|&i| !used[i] && beside(&lines[i]) && lines[i].top >= r.b[3] - 2.0) {
        return i;
    }
    if let Some(i) = range.clone().rev().find(|&i| !used[i] && beside(&lines[i]) && lines[i].bottom <= r.b[1] + 2.0) {
        return i + 1;
    }
    range.start
}

/// A list item set with a wide gap after its marker ("•      text"), which is not a table row.
fn list_item(l: &Line) -> bool {
    let segs = l.segments();
    segs.len() == 2 && list_marker(&format!("{} ", glyph_text(&l.glyphs[segs[0].2.clone()]))).is_some_and(|m| m.1 == glyph_text(&l.glyphs[segs[0].2.clone()]).len() + 1)
}

/// Runs of lines that look like a table: two or more lines whose wide-gap pieces fall in shared columns.
fn find_tables(lines: &[Line], used: &[bool], body: f64) -> Vec<(usize, usize, Vec<(f64, f64)>)> {
    let mut out = vec![];
    let mut i = 0;
    while i < lines.len() {
        let segs = lines[i].segments();
        if used[i] || segs.len() < 2 || lines[i].mono > 0.5 || lines[i].size > body * 1.3 || list_item(&lines[i]) {
            i += 1;
            continue;
        }
        let mut cols: Vec<(f64, f64)> = segs.iter().map(|s| (s.0, s.1)).collect();
        let mut multi = 1;
        let mut j = i + 1;
        while j < lines.len() && !used[j] && lines[j].page == lines[i].page && lines[j].top > lines[j - 1].top && lines[j].top - lines[j - 1].bottom < body * 2.5 && lines[j].mono <= 0.5 && !list_item(&lines[j]) {
            let s = lines[j].segments();
            let mut hits: Vec<Option<usize>> = vec![];
            let mut ok = true;
            for seg in &s {
                let over: Vec<usize> = cols.iter().enumerate().filter(|(_, c)| seg.0 < c.1 + 4.0 && seg.1 > c.0 - 4.0).map(|(k, _)| k).collect();
                match over.len() {
                    0 => hits.push(None),
                    1 => hits.push(Some(over[0])),
                    _ => {
                        ok = false;
                        break;
                    }
                }
            }
            if !ok || s.is_empty() {
                break;
            }
            if s.len() < 2 {
                // a cell's wrapped line: only inside a table that carries on
                let next_multi = lines.get(j + 1).is_some_and(|n| n.page == lines[j].page && n.segments().len() >= 2);
                if !next_multi || hits[0].is_none() {
                    break;
                }
            } else {
                multi += 1;
            }
            for (seg, h) in s.iter().zip(&hits) {
                match h {
                    Some(c) => {
                        cols[*c].0 = cols[*c].0.min(seg.0);
                        cols[*c].1 = cols[*c].1.max(seg.1);
                    }
                    None => cols.push((seg.0, seg.1)),
                }
            }
            j += 1;
        }
        if multi >= 2 && cols.len() >= 2 {
            cols.sort_by(|a, b| a.0.total_cmp(&b.0));
            out.push((i, j, cols));
            i = j;
        } else {
            i += 1;
        }
    }
    out
}

enum Item {
    P(Para),
    T(usize),
    R(usize),
}

pub fn convert(pages: &[PPage], opts: &Options, h: &dyn Helper, render: Render) -> Document {
    let mut lines: Vec<Line> = vec![];
    for (k, p) in pages.iter().enumerate() {
        lines.extend(lines_of(k, p));
    }
    let npages = pages.len().max(1);
    // running headers and footers: the same line (numbers aside) near the edge of many pages
    if opts.drop_headers {
        let mut seen: HashMap<String, usize> = HashMap::new();
        for l in &lines {
            let ph = pages[l.page].height;
            if l.top < ph * 0.09 || l.bottom > ph * 0.91 {
                *seen.entry(normalize_repeat(&l.text)).or_insert(0) += 1;
            }
        }
        let limit = ((npages as f64) * 0.4).ceil().max(3.0) as usize;
        lines.retain(|l| {
            let ph = pages[l.page].height;
            let edge = l.top < ph * 0.09 || l.bottom > ph * 0.91;
            !(edge && npages >= 3 && seen.get(&normalize_repeat(&l.text)).copied().unwrap_or(0) >= limit)
        });
        drop_page_numbers(&mut lines, pages);
    }
    if lines.is_empty() && pages.iter().all(|p| p.images.is_empty()) {
        return Document::default();
    }
    let mut sizes: HashMap<i64, usize> = HashMap::new();
    for l in &lines {
        *sizes.entry((l.size * 2.0).round() as i64).or_insert(0) += l.text.chars().count();
    }
    let body = sizes.iter().max_by_key(|x| (x.1, x.0)).map(|x| *x.0 as f64 / 2.0).unwrap_or(10.0);
    // footnotes: small text at the bottom of a page or column, moved to the end so it does not cut paragraphs
    let mut notes: Vec<Line> = vec![];
    let mut kept = vec![];
    for (i, l) in lines.iter().enumerate() {
        let ph = pages[l.page].height;
        let small = l.size < body * 0.88;
        let low = l.top > ph * 0.6;
        let next_ok = lines.get(i + 1).is_none_or(|n| n.page != l.page || n.top < l.top - l.size || (n.size < body * 0.88 && n.top > l.top));
        let starts_note = l.text.chars().next().is_some_and(|c| c.is_ascii_digit() || "*†‡§".contains(c));
        let in_notes = notes.last().is_some_and(|n: &Line| n.page == l.page && small);
        if small && low && next_ok && l.mono < 0.5 && (starts_note || in_notes) {
            notes.push(l.clone());
        } else {
            kept.push(l.clone());
        }
    }
    let lines = kept;
    let ranges = page_ranges(&lines, pages.len());
    let cols: Vec<Vec<Col>> = ranges.iter().map(|r| page_columns(&lines[r.clone()], body)).collect();
    let mut used = vec![false; lines.len()];
    // pictures: drawings and equations drawn from the page, and the PDF's own images
    let mut taken: Vec<Vec<bool>> = pages.iter().map(|p| vec![false; p.images.len()]).collect();
    let mut regions: Vec<Region> = vec![];
    if opts.images {
        regions.extend(figures(pages, &lines, &ranges, body, &mut used, &mut taken, render, opts.debug));
    }
    regions.extend(equations(&lines, &ranges, &cols, body, &mut used, render));
    if opts.images {
        for (k, p) in pages.iter().enumerate() {
            for (j, im) in p.images.iter().enumerate() {
                if taken[k][j] || im.x1 - im.x0 <= 24.0 || im.bottom - im.top <= 24.0 {
                    continue;
                }
                let b = [im.x0, im.top, im.x1, im.bottom];
                // a page-size picture under the text is a background or a scan, not a figure
                let big = (b[2] - b[0]) * (b[3] - b[1]) > 0.6 * p.width * p.height;
                if big && ranges[k].clone().filter(|&i| center_in(&lines[i], &b, 0.0)).count() >= 3 {
                    continue;
                }
                regions.push(Region { page: k, b, kind: Kind::Picture, data: im.data.clone(), alt: String::new(), pos: 0 });
            }
        }
    }
    for r in regions.iter_mut() {
        if r.kind != Kind::Math {
            r.pos = place(&lines, &ranges, &used, r);
        }
    }
    regions.sort_by(|a, b| (a.pos, a.page).cmp(&(b.pos, b.page)).then(a.b[1].total_cmp(&b.b[1])));
    let tables = if opts.tables { find_tables(&lines, &used, body) } else { vec![] };
    let mut gaps: Vec<f64> = lines.windows(2).filter(|w| w[0].page == w[1].page && (w[0].size - body).abs() < 0.6 && (w[1].size - body).abs() < 0.6)
        .map(|w| w[1].top - w[0].top).filter(|g| *g > 0.0 && *g < body * 3.0).collect();
    gaps.sort_by(f64::total_cmp);
    let leading = gaps.get(gaps.len() / 2).copied().unwrap_or(body * 1.2);
    // paragraphs, with tables and pictures in their places
    let mut items: Vec<Item> = vec![];
    let mut deferred: Vec<usize> = vec![]; // drawings and pictures waiting for the paragraph they cut to end
    let mut force_new = false;
    let mut prev_i: Option<usize> = None;
    let mut ri = 0;
    let mut i = 0;
    while i <= lines.len() {
        while ri < regions.len() && regions[ri].pos <= i {
            if regions[ri].kind == Kind::Math {
                items.extend(deferred.drain(..).map(Item::R));
                items.push(Item::R(ri));
                force_new = true;
            } else {
                deferred.push(ri);
            }
            ri += 1;
        }
        if i == lines.len() {
            break;
        }
        if used[i] {
            i += 1;
            continue;
        }
        if let Some(t) = tables.iter().position(|t| t.0 == i) {
            items.extend(deferred.drain(..).map(Item::R));
            items.push(Item::T(t));
            force_new = true;
            prev_i = Some(tables[t].1 - 1);
            i = tables[t].1;
            continue;
        }
        let l = &lines[i];
        let heading_like = has_words(&l.text) && (l.size >= body * 1.15 || (l.bold > 0.9 && l.text.split_whitespace().count() <= 14 && !ends_sentence(&l.text) && l.size >= body * 0.95));
        let marker = list_marker(&l.text);
        let mut new = true;
        if let (false, Some(Item::P(p)), Some(pi)) = (force_new, items.last(), prev_i) {
            let prev = &lines[pi];
            let p_heading = p.style == "h";
            let same_size = (prev.size - l.size).abs() < 0.12 * body;
            // a picture between the two lines does not part them
            let passed = regions.iter().any(|r| r.kind != Kind::Math && r.pos > pi && r.pos <= i && r.page == l.page && r.page == prev.page);
            let mut gap = l.top - prev.bottom;
            let mut step = l.top - prev.top;
            if passed {
                gap = gap.min(leading * 0.3);
                step = step.min(leading);
            }
            let moved = l.page != prev.page || step < -prev.size; // the next page or column
            let pc = column_of(&cols[prev.page], prev);
            let lc = column_of(&cols[l.page], l);
            // the previous line was full if this line's first word would not have fitted on it
            let first_word = l.glyphs.iter().take_while(|g| !g.space).last().map(|g| g.x1 - l.x0).unwrap_or(0.0);
            let room = pc.right - prev.x1;
            let prev_full = room < first_word + 0.25 * body;
            if p.style == "code" {
                new = !(l.mono > 0.7 && !moved && gap < leading * 1.6);
            } else if moved {
                let starts_low = l.text.chars().next().is_some_and(|c| c.is_lowercase() || c.is_ascii_digit() || ",;)".contains(c));
                let ends = ends_sentence(&prev.text) && !starts_low && (!prev_full || l.x0 > lc.left + 0.9 * body);
                new = p_heading || heading_like || marker.is_some() || !same_size || l.mono > 0.7 || ends;
            } else if !same_size || heading_like != p_heading || marker.is_some() || l.mono > 0.7 {
                new = true;
            } else if p_heading {
                new = !(gap < leading * 0.6 && !ends_sentence(&prev.text));
            } else if gap > leading * 0.55 && step > leading * 1.35 {
                new = true;
            } else if p.list.is_some() {
                // a list item continues on a line that starts where its text started
                new = !(prev_full && (l.x0 - p.item_x).abs() < 0.8 * body);
            } else {
                // indented against the paragraph's other lines in this column (its first line may be
                // indented, or hang out to the left)
                let col: Vec<&Line> = p.lines.iter().filter(|x| x.page == l.page && x.x0 < l.x1 && x.x1 > l.x0).collect();
                let indented = match col.len() {
                    0 => false,
                    1 => l.x0 > col[0].x0 + 0.9 * body && ends_sentence(&prev.text),
                    _ => l.x0 > col[1..].iter().map(|x| x.x0).fold(f64::INFINITY, f64::min) + 0.9 * body,
                };
                let short_end = !prev_full && (ends_sentence(&prev.text) || room > 0.25 * (pc.right - pc.left));
                new = indented || short_end;
            }
        }
        if opts.debug {
            eprintln!("{i} p{} x {:.1}-{:.1} y {:.1}-{:.1} size {:.1} bold {:.1} new {new} {:?}", l.page, l.x0, l.x1, l.top, l.bottom, l.size, l.bold, l.text.chars().take(50).collect::<String>());
        }
        if new {
            items.extend(deferred.drain(..).map(Item::R));
            let style = if l.mono > 0.7 { "code" } else if heading_like { "h" } else { "normal" };
            let (list, item_x) = match (&marker, style) {
                (Some((kind, len)), "normal") => {
                    // the x of the first character after the marker
                    let skip = l.text[..*len].chars().filter(|c| !c.is_whitespace()).count();
                    let x = l.glyphs.iter().filter(|g| !g.space).nth(skip).map(|g| g.x0).unwrap_or(l.x0);
                    (Some((kind.clone(), 0u32)), x)
                }
                _ => (None, l.x0),
            };
            items.push(Item::P(Para { lines: vec![l.clone()], style: style.into(), list, item_x }));
        } else if let Some(Item::P(p)) = items.last_mut() {
            p.lines.push(l.clone());
        }
        force_new = false;
        prev_i = Some(i);
        i += 1;
    }
    items.extend(deferred.drain(..).map(Item::R));
    // heading levels from their sizes; the biggest text at the top of the first page is the title,
    // and centred lines just under it (authors, a date) are subtitles
    let mut hsizes: Vec<i64> = items.iter().filter_map(|it| if let Item::P(p) = it { if p.style == "h" { Some((p.lines[0].size * 2.0).round() as i64) } else { None } } else { None }).collect();
    hsizes.sort_unstable_by(|a, b| b.cmp(a));
    hsizes.dedup();
    let first = items.iter().position(|it| matches!(it, Item::P(p) if p.lines[0].page == 0));
    let title = first.filter(|k| matches!(&items[*k], Item::P(p) if p.style == "h" && (p.lines[0].size * 2.0).round() as i64 == hsizes[0] && p.lines[0].size >= body * 1.4));
    let mut after_title = false;
    for (k, it) in items.iter_mut().enumerate() {
        let Item::P(p) = it else {
            after_title = false;
            continue;
        };
        let pw = pages[p.lines[0].page].width;
        let mid = (p.lines[0].x0 + p.lines[0].x1) / 2.0;
        let centred = (mid - pw / 2.0).abs() < pw * 0.05 && (p.lines[0].x1 - p.lines[0].x0) < pw * 0.7;
        if p.style != "h" {
            after_title = false;
            continue;
        }
        let s = (p.lines[0].size * 2.0).round() as i64;
        let rank = hsizes.iter().position(|x| *x == s).unwrap_or(0);
        let words = p.lines.iter().map(|l| l.text.split_whitespace().count()).sum::<usize>();
        if words > 25 {
            p.style = "normal".into();
            continue;
        }
        if Some(k) == title {
            p.style = "title".into();
            after_title = true;
        } else if after_title && centred && p.lines[0].page == 0 && p.lines[0].bold < 0.5 {
            p.style = "subtitle".into();
        } else {
            after_title = false;
            // with a title, the next size down is level 1
            p.style = format!("h{}", (rank + if title.is_some() { 0 } else { 1 }).clamp(1, 6));
        }
    }
    // list levels from indentation
    let mut list_lefts: Vec<f64> = vec![];
    for it in items.iter_mut() {
        let Item::P(p) = it else {
            list_lefts.clear();
            continue;
        };
        if p.list.is_none() {
            list_lefts.clear();
            continue;
        }
        let x = p.lines[0].x0;
        while list_lefts.last().is_some_and(|l| x < *l - 4.0) {
            list_lefts.pop();
        }
        if list_lefts.last().is_none_or(|l| x > *l + 6.0) {
            list_lefts.push(x);
        }
        if let Some((_, level)) = &mut p.list {
            *level = (list_lefts.len() as u32).saturating_sub(1).min(8);
        }
    }
    // build the document
    let mut doc = Document { size: body.round(), ..Default::default() };
    if let Some(p0) = pages.first() {
        doc.page.width = p0.width;
        doc.page.height = p0.height;
    }
    for it in &items {
        let p = match it {
            Item::R(r) => {
                doc.blocks.push(picture(&regions[*r]));
                continue;
            }
            Item::T(t) => {
                let (a, b, columns) = &tables[*t];
                doc.blocks.push(Block::Table(build_table(&lines[*a..*b], columns, h)));
                continue;
            }
            Item::P(p) => p,
        };
        if p.style == "code" {
            let left = p.lines.iter().map(|l| l.x0).fold(f64::INFINITY, f64::min);
            let cw = p.lines.iter().flat_map(|l| l.glyphs.iter().filter(|g| !g.space).map(|g| g.x1 - g.x0)).fold(0.0, f64::max).max(body * 0.5);
            let text = p.lines.iter().map(|l| format!("{}{}", " ".repeat(((l.x0 - left) / cw).round().max(0.0) as usize), l.text)).collect::<Vec<_>>().join("\n");
            doc.blocks.push(Block::CodeBlock(CodeBlock { text: textclean::ligatures(&text), lang: String::new() }));
            continue;
        }
        let mut content = paragraph_runs(&p.lines, opts.fix_words, h);
        if p.list.is_some() {
            strip_marker(&mut content);
        }
        let content = strip_content(merge_runs(content));
        let mut style = p.style.clone();
        let text = inline_text(&content, false);
        if style == "normal" && caption_re().is_match(text.trim()) && text.len() < 400 {
            style = "caption".into();
        }
        let first = &p.lines[0];
        let c = column_of(&cols[first.page], first);
        let f = text_frame(&cols[first.page]);
        let mid = (first.x0 + first.x1) / 2.0;
        let centred_in = |c: Col| {
            let (cm, cw) = ((c.left + c.right) / 2.0, c.right - c.left);
            (mid - cm).abs() < cw * 0.04 && first.x1 - first.x0 < cw * 0.75 && first.x0 - c.left > 2.0 * body
        };
        let centred = p.lines.len() <= 3 && (centred_in(f) || centred_in(c));
        if style == "normal" && p.list.is_none() && !centred {
            // set in from the column's edge on every line: a quotation
            let inset = p.lines.iter().all(|l| l.x0 >= column_of(&cols[l.page], l).left + 1.8 * body);
            if inset && (p.lines.len() >= 2 || first.italic > 0.5) {
                style = "quote".into();
            }
        }
        let mut para = Paragraph { content, style: style.clone(), list: p.list.clone(), ..Default::default() };
        if is_heading(&style) || style == "quote" {
            for x in para.content.iter_mut() {
                if let Inline::Run(r) = x {
                    if is_heading(&style) {
                        r.b = false;
                        r.size = None;
                    } else {
                        r.i = false;
                    }
                }
            }
        }
        if centred && !is_heading(&style) {
            para.align = Some("center".into());
        }
        doc.blocks.push(Block::Paragraph(para));
    }
    if !notes.is_empty() {
        doc.blocks.push(Block::Rule(Rule {}));
        let mut cur: Vec<Line> = vec![];
        let flush = |cur: &mut Vec<Line>, doc: &mut Document| {
            if cur.is_empty() {
                return;
            }
            let content = strip_content(merge_runs(paragraph_runs(&std::mem::take(cur), false, &textclean::NoHelper)));
            doc.blocks.push(Block::Paragraph(Paragraph { content, style: "caption".into(), ..Default::default() }));
        };
        for l in notes {
            if l.text.chars().next().is_some_and(|c| c.is_ascii_digit() || "*†‡§".contains(c)) {
                flush(&mut cur, &mut doc);
            }
            cur.push(l);
        }
        flush(&mut cur, &mut doc);
    }
    if let Some(Block::Paragraph(p)) = doc.blocks.iter().find(|b| matches!(b, Block::Paragraph(p) if p.style == "title" || p.style == "h1")) {
        doc.title = p.text().trim().chars().take(200).collect();
    }
    doc
}

fn build_table(lines: &[Line], columns: &[(f64, f64)], h: &dyn Helper) -> Table {
    let mut t = Table { rows: vec![], header: false, widths: None };
    for l in lines {
        let mut row: Vec<Vec<Paragraph>> = vec![vec![Paragraph::default()]; columns.len()];
        for (x0, x1, range) in l.segments() {
            let overlap = |c: &(f64, f64)| x1.min(c.1) - x0.max(c.0);
            let col = (0..columns.len()).max_by(|a, b| overlap(&columns[*a]).total_cmp(&overlap(&columns[*b]))).unwrap_or(0);
            let part = Line { glyphs: l.glyphs[range].to_vec(), ..l.clone() };
            let content = strip_content(merge_runs(paragraph_runs(&[part], false, h)));
            let cell = &mut row[col][0];
            if !cell.content.is_empty() {
                cell.content.push(Inline::Run(Run::new(" ")));
            }
            cell.content.extend(content);
        }
        t.rows.push(row);
    }
    t.header = lines.first().is_some_and(|l| l.bold > 0.8) || lines.len() > 2 && lines[0].bold > lines[1].bold + 0.5;
    t
}

fn picture(r: &Region) -> Block {
    let ext = crate::imaging::sniff(&r.data).to_string();
    let name = if r.kind == Kind::Math { "equation.png" } else { "figure.png" };
    Block::Paragraph(Paragraph {
        content: vec![Inline::Image(Image { data: r.data.clone(), ext, width: r.b[2] - r.b[0], height: r.b[3] - r.b[1], alt: r.alt.clone(), name: name.into() })],
        align: Some("center".into()),
        ..Default::default()
    })
}

/// Remove a list marker ("•", "1.", "(a)") from the start of a paragraph's runs.
fn strip_marker(content: &mut Vec<Inline>) {
    let lead: String = content.iter().take_while(|x| matches!(x, Inline::Run(_))).map(|x| if let Inline::Run(r) = x { r.text.clone() } else { String::new() }).collect();
    let Some(m) = marker_re().find(&lead) else { return };
    let mut n = m.end();
    while n > 0 {
        let Some(Inline::Run(r)) = content.first_mut() else { break };
        if r.text.len() <= n {
            n -= r.text.len();
            content.remove(0);
        } else {
            let mut cut = n;
            while !r.text.is_char_boundary(cut) {
                cut += 1;
            }
            r.text = r.text[cut..].to_string();
            n = 0;
        }
    }
}

/// The runs of some lines joined into one paragraph: hyphenated words rejoined, styles from the fonts,
/// superscripts and subscripts from size and baseline.
fn paragraph_runs(lines: &[Line], fix_words: bool, h: &dyn Helper) -> Vec<Inline> {
    let mut pieces: Vec<(String, bool, bool, i8)> = vec![]; // text, bold, italic, +1 sup / -1 sub, 9 = line joint
    let n = lines.len();
    for (k, l) in lines.iter().enumerate() {
        let main = l.size;
        for g in &l.glyphs {
            let level: i8 = if !g.space && g.size < main * 0.82 {
                if g.base < l.base - 0.15 * main {
                    1
                } else if g.base > l.base + 0.08 * main {
                    -1
                } else {
                    0
                }
            } else {
                0
            };
            let c = if g.space { ' ' } else { g.ch };
            match pieces.last_mut() {
                Some(last) if last.1 == g.bold && last.2 == g.italic && last.3 == level => last.0.push(c),
                _ => pieces.push((c.to_string(), g.bold, g.italic, level)),
            }
        }
        if k + 1 < n {
            pieces.push(("\u{1}".into(), false, false, 9));
        }
    }
    let full: String = pieces.iter().map(|p| p.0.as_str()).collect();
    let mut joints: Vec<String> = vec![];
    for (pos, _) in full.match_indices('\u{1}') {
        let before = full[..pos].trim_end_matches(' ');
        let after = full[pos + 1..].trim_start_matches(' ');
        let hyphen = before.ends_with('-') || before.ends_with('\u{2010}') || before.ends_with('\u{ad}');
        let rep = if hyphen && after.chars().next().is_some_and(|c| c.is_lowercase()) {
            let stem = before.trim_end_matches(['-', '\u{2010}', '\u{ad}']);
            let lw: String = stem.chars().rev().take_while(|c| c.is_alphabetic()).collect::<Vec<_>>().into_iter().rev().collect();
            let rw: String = after.chars().take_while(|c| c.is_alphabetic()).collect();
            let cb: String = stem[..stem.len() - lw.len()].chars().rev().take(160).collect::<Vec<_>>().into_iter().rev().collect();
            let ca: String = after[rw.len()..].chars().take(160).collect();
            if textclean::dehyphen(&lw, &rw, &cb, &ca, h).contains('-') {
                "-"
            } else {
                ""
            }
        } else if hyphen {
            "-"
        } else {
            " "
        };
        joints.push(rep.to_string());
    }
    let mut out: Vec<Inline> = vec![];
    let mut ji = 0;
    for (text, b, i, level) in pieces {
        if level == 9 {
            let rep = joints.get(ji).cloned().unwrap_or_else(|| " ".into());
            ji += 1;
            if let Some(Inline::Run(r)) = out.last_mut() {
                let mut t = r.text.trim_end_matches(' ').to_string();
                if rep != " " {
                    t = t.trim_end_matches(['-', '\u{2010}', '\u{ad}']).to_string();
                    t.push_str(&rep);
                } else {
                    t.push(' ');
                }
                r.text = t;
            }
            continue;
        }
        let mut t = textclean::ligatures(&text);
        let glue = matches!(out.last(), Some(Inline::Run(r)) if r.text.ends_with(' ') || r.text.ends_with('-') && ji > 0) || out.is_empty();
        if glue {
            t = t.trim_start_matches(' ').to_string();
        }
        out.push(Inline::Run(Run { text: t, b, i, sup: level > 0, sub: level < 0, ..Default::default() }));
    }
    let mut out = merge_runs(out);
    let spaces = Regex::new(" {2,}").unwrap();
    for x in out.iter_mut() {
        if let Inline::Run(r) = x {
            let collapsed = textclean::collapse_spaced(&r.text);
            r.text = spaces.replace_all(&collapsed, " ").into_owned();
            if fix_words {
                let fixed: Vec<String> = r.text.split(' ').map(|w| {
                    let core: String = w.trim_matches(|c: char| !c.is_alphabetic()).to_string();
                    match textclean::split_run_together(&core, h) {
                        Some(s) => w.replacen(&core, &s, 1),
                        None => w.to_string(),
                    }
                }).collect();
                r.text = fixed.join(" ");
            }
        }
    }
    out
}
